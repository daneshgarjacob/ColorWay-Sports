#!/usr/bin/env node
// Daily Logo (/quiz/daily): the schedule and the three crops per day.
//
// The pool is every piece in the PUBLISHED logo quizzes: the quiz JSON files
// that lib/quiz.ts actually imports (commented-out imports, the hidden NHL and
// MLB part-1 quizzes, are skipped). Pieces go into a fixed, seeded shuffle, so
// every reader gets the same piece on the same Eastern date and nothing repeats
// until the whole pool has been used.
//
// Writes:
//   content/data/daily-logo/schedule.json   ordered list of { quiz, n, key }
//   public/quiz/daily/<key>-1.webp          the piece (same crop as the quiz)
//   public/quiz/daily/<key>-2.webp          a larger crop (after guess 1 misses)
//   public/quiz/daily/<key>-3.webp          larger again (after guess 2 misses)
//
// The key is a salted hash, so neither the file names nor the schedule say
// which team a day is. Rerunning is safe: days already in the schedule keep
// their place, and pieces from newly published quizzes are shuffled onto the
// END, so past and upcoming days never change. Every image is capped at 40 KB.
//
// Needs the logo source folders under ~/Desktop/ColorWay Sports/social (same as
// build-quiz-assets.mjs), so it runs on Jake's machine; the output is committed.
//
//   node scripts/build-daily-logo.mjs

import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync, statSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOCIAL = join(os.homedir(), "Desktop/ColorWay Sports/social");
const SCHEDULE = join(root, "content/data/daily-logo/schedule.json");
const OUT = join(root, "public/quiz/daily");
const MAX_BYTES = 40 * 1024;
const PX = 320;
// How much wider than the original piece the two reveal crops are.
const ZOOMS = [1, 2, 3.6];

// FNV-1a, 32-bit. Same function as lib/dailyLogoHash.ts.
function fnv(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

function mulberry32(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Published quizzes = uncommented JSON imports in lib/quiz.ts.
const quizTs = readFileSync(join(root, "lib/quiz.ts"), "utf8");
const published = [...quizTs.matchAll(/^import \w+ from "@\/content\/data\/quizzes\/([\w-]+)\.json";/gm)].map((m) => m[1]);
const quizzes = published.map((slug) => JSON.parse(readFileSync(join(root, "content/data/quizzes", `${slug}.json`), "utf8")));
// The daily pool is logo quizzes only (jersey and old-logo quizzes have their own pages).
const logoQuizzes = quizzes.filter((q) => (q.type ?? "logo") === "logo");

const existing = existsSync(SCHEDULE) ? JSON.parse(readFileSync(SCHEDULE, "utf8")) : null;
const salt = existing?.salt ?? fnv(`colorway-daily-${Date.now()}`);
const epoch = existing?.epoch ?? "2026-11-16";
const days = existing?.days ?? [];
const have = new Set(days.map((d) => `${d.quiz}#${d.n}`));

const fresh = [];
for (const q of logoQuizzes) {
  q.items.forEach((item, i) => {
    const id = `${q.slug}#${i + 1}`;
    if (!have.has(id)) fresh.push({ quiz: q.slug, n: i + 1, team: item.team, league: q.leagueName });
  });
}

// Seeded Fisher-Yates, seed derived from the salt and how many days exist, so a
// rerun with nothing new is a no-op and an append is still deterministic.
const rand = mulberry32(parseInt(fnv(`${salt}:${days.length}`), 16));
for (let i = fresh.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [fresh[i], fresh[j]] = [fresh[j], fresh[i]];
}
// Light pass: no same team, and no same league, on back-to-back days where a
// later piece can be swapped in.
const teamOf = (d) => d.team ?? quizzes.find((q) => q.slug === d.quiz)?.items[d.n - 1]?.team;
const leagueOf = (d) => d.league ?? quizzes.find((q) => q.slug === d.quiz)?.leagueName;
const all = [...days, ...fresh];
for (let i = days.length; i < all.length; i++) {
  const prev = all[i - 1];
  if (!prev) continue;
  const clash = (d) => teamOf(d) === teamOf(prev) || leagueOf(d) === leagueOf(prev);
  if (!clash(all[i])) continue;
  const k = all.findIndex((d, j) => j > i && !clash(d));
  if (k > 0) [all[i], all[k]] = [all[k], all[i]];
}

const out = all.map((d) => ({ quiz: d.quiz, n: d.n, key: d.key ?? fnv(`${salt}:${d.quiz}:${d.n}`) }));
mkdirSync(dirname(SCHEDULE), { recursive: true });
writeFileSync(
  SCHEDULE,
  JSON.stringify(
    {
      note: "Generated by scripts/build-daily-logo.mjs. Day 1 = epoch (US Eastern). Never reorder: append only.",
      epoch,
      salt,
      days: out,
    },
    null,
    1,
  ) + "\n",
);

// Crops.
mkdirSync(OUT, { recursive: true });
let failed = false;
let total = 0;
for (const d of out) {
  const q = quizzes.find((x) => x.slug === d.quiz);
  if (!q) {
    console.error(`✗ schedule names ${d.quiz}, which is not a published quiz`);
    failed = true;
    continue;
  }
  const item = q.items[d.n - 1];
  const logo = join(SOCIAL, q.source, "logos", `${item.abbr}.png`);
  const { width: w, height: h } = await sharp(logo).metadata();
  const [x0, y0, x1, y1] = item.box;
  // Same integer math as build-quiz-assets.mjs, so crop 1 is the quiz piece.
  const left = Math.floor(x0 * w);
  const top = Math.floor(y0 * h);
  const cw = Math.floor(x1 * w) - left;
  const ch = Math.floor(y1 * h) - top;
  const cx = left + cw / 2;
  const cy = top + ch / 2;
  const base = Math.max(cw, ch);

  for (const [zi, zoom] of ZOOMS.entries()) {
    const side = Math.min(Math.round(base * zoom), w, h);
    // Keep the box inside the logo by sliding it, so it stays centred where possible.
    const l = Math.max(0, Math.min(w - side, Math.round(cx - side / 2)));
    const t = Math.max(0, Math.min(h - side, Math.round(cy - side / 2)));
    const file = join(OUT, `${d.key}-${zi + 1}.webp`);
    await sharp(logo)
      .ensureAlpha()
      .extract({ left: l, top: t, width: side, height: side })
      .resize(PX, PX, { kernel: "lanczos3" })
      .webp({ quality: 84, alphaQuality: 90 })
      .toFile(file);
    const size = statSync(file).size;
    total += size;
    if (size > MAX_BYTES) {
      console.error(`✗ ${file} is ${(size / 1024).toFixed(1)} KB (cap 40 KB)`);
      failed = true;
    }
  }
}
console.log(`✓ Daily Logo: ${out.length} days (${fresh.length} new), ${(total / 1024).toFixed(0)} KB of crops`);
if (failed) process.exit(1);
